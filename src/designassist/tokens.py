"""`da tokens`: the design's colour and font tokens (brand kit + design.json) as files other tools
read: CSS custom properties, SCSS variables, a Tailwind theme, plain JSON, Tokens Studio JSON
(Figma), and an Adobe Swatch Exchange (.ase) file for Illustrator / Photoshop / InDesign.

Authored CMYK values (token {"hex", "cmyk"}) go into the .ase as CMYK swatches; a token with a
`pantone` name becomes a spot swatch with that name.
"""
from __future__ import annotations

import json
import re
import struct
from pathlib import Path

from . import colors as C


def _key(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def collect(ctx, scales: bool = False) -> dict:
    """{"colors": {name: Color}, "fonts": {name: {family, weight, italic}}, "scales": {name: {step: hex}}}."""
    cols = {}
    for name in ctx.colors:
        try:
            c = ctx.color(f"${name}")
        except C.ColorError:
            continue
        if c is not None:
            cols[name] = c
    fonts = {}
    for name, spec in ctx.fonts.items():
        s = dict(spec) if isinstance(spec, dict) else {"family": spec}
        s.setdefault("weight", 400)
        fonts[name] = s
    out = {"colors": cols, "fonts": fonts, "scales": {}}
    if scales:
        from .colortools import scale

        for name, c in cols.items():
            if name not in ("ink", "paper"):
                out["scales"][name] = scale(c)
    return out


def _raw(name: str, ctx) -> dict:
    v = ctx.colors.get(name)
    return v if isinstance(v, dict) else {}


def to_css(t: dict, ctx) -> str:
    lines = [":root {"]
    for n, c in t["colors"].items():
        val = c.hex if c.a >= 1 else f"rgba({c.r}, {c.g}, {c.b}, {c.a:.3g})"
        lines.append(f"  --color-{_key(n)}: {val};")
    for n, sc in t["scales"].items():
        for step, hx in sc.items():
            lines.append(f"  --color-{_key(n)}-{step}: {hx};")
    for n, f in t["fonts"].items():
        lines.append(f"  --font-{_key(n)}: \"{f['family']}\", system-ui, sans-serif;")
        lines.append(f"  --font-{_key(n)}-weight: {f['weight']};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def to_scss(t: dict, ctx) -> str:
    lines = []
    for n, c in t["colors"].items():
        lines.append(f"$color-{_key(n)}: {c.hex};")
    for n, sc in t["scales"].items():
        for step, hx in sc.items():
            lines.append(f"$color-{_key(n)}-{step}: {hx};")
    for n, f in t["fonts"].items():
        lines.append(f"$font-{_key(n)}: \"{f['family']}\", system-ui, sans-serif;")
        lines.append(f"$font-{_key(n)}-weight: {f['weight']};")
    return "\n".join(lines) + "\n"


def to_tailwind(t: dict, ctx) -> str:
    colors: dict = {}
    for n, c in t["colors"].items():
        k = _key(n)
        if n in t["scales"]:
            colors[k] = {"DEFAULT": c.hex, **t["scales"][n]}
        else:
            colors[k] = c.hex
    fam = {_key(n): [f["family"], "system-ui", "sans-serif"] for n, f in t["fonts"].items()}
    theme = {"theme": {"extend": {"colors": colors, "fontFamily": fam}}}
    return ("/** @type {import('tailwindcss').Config} */\n// generated by `da tokens`; Tailwind v4: use the CSS output in @theme\n"
            "module.exports = " + json.dumps(theme, indent=2, ensure_ascii=False) + ";\n")


def to_json(t: dict, ctx) -> str:
    data = {"colors": {}, "fonts": t["fonts"], "scales": t["scales"]}
    for n, c in t["colors"].items():
        raw = _raw(n, ctx)
        data["colors"][n] = {"hex": c.hex, "alpha": c.a, "cmyk": list(C.to_cmyk(c)),
                             "cmyk_authored": bool(c.cmyk), **({"pantone": raw["pantone"]} if raw.get("pantone") else {})}
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def to_figma(t: dict, ctx) -> str:
    """Tokens Studio for Figma format (single 'global' set)."""
    g: dict = {"color": {}, "fontFamilies": {}, "fontWeights": {}}
    for n, c in t["colors"].items():
        g["color"][_key(n)] = {"value": c.hex, "type": "color"}
    for n, sc in t["scales"].items():
        g["color"][f"{_key(n)}-scale"] = {s: {"value": hx, "type": "color"} for s, hx in sc.items()}
    for n, f in t["fonts"].items():
        g["fontFamilies"][_key(n)] = {"value": f["family"], "type": "fontFamilies"}
        g["fontWeights"][_key(n)] = {"value": str(f["weight"]), "type": "fontWeights"}
    return json.dumps({"global": g}, indent=2, ensure_ascii=False) + "\n"


# --- Adobe Swatch Exchange ---------------------------------------------------------------------

def _ase_name(name: str) -> bytes:
    s = name + "\0"
    return struct.pack(">H", len(s)) + s.encode("utf-16-be")


def ase_bytes(group: str, swatches: list[dict]) -> bytes:
    """swatches: [{"name", "rgb": (r,g,b 0-255)} or {"name", "cmyk": (c,m,y,k 0-100)}, "spot": bool]."""
    blocks = []
    name = _ase_name(group)
    blocks.append(struct.pack(">HI", 0xC001, len(name)) + name)
    for sw in swatches:
        body = _ase_name(sw["name"])
        if "cmyk" in sw:
            body += b"CMYK" + struct.pack(">4f", *[v / 100 for v in sw["cmyk"]])
        else:
            body += b"RGB " + struct.pack(">3f", *[v / 255 for v in sw["rgb"]])
        body += struct.pack(">H", 1 if sw.get("spot") else 0)  # 0 global, 1 spot, 2 normal
        blocks.append(struct.pack(">HI", 0x0001, len(body)) + body)
    blocks.append(struct.pack(">HI", 0xC002, 0))
    return b"ASEF" + struct.pack(">HHI", 1, 0, len(blocks)) + b"".join(blocks)


def to_ase(t: dict, ctx, group: str) -> bytes:
    sws = []
    for n, c in t["colors"].items():
        raw = _raw(n, ctx)
        label = raw.get("pantone") or n
        if c.cmyk:
            sws.append({"name": label, "cmyk": c.cmyk, "spot": bool(raw.get("pantone"))})
        else:
            sws.append({"name": label, "rgb": (c.r, c.g, c.b), "spot": bool(raw.get("pantone"))})
    for n, sc in t["scales"].items():
        for step, hx in sc.items():
            c = C.parse(hx)
            sws.append({"name": f"{n}-{step}", "rgb": (c.r, c.g, c.b)})
    return ase_bytes(group, sws)


FORMATS = {"css": ("tokens.css", to_css), "scss": ("_tokens.scss", to_scss), "tailwind": ("tailwind.tokens.js", to_tailwind),
           "json": ("tokens.json", to_json), "figma": ("tokens.studio.json", to_figma), "ase": ("swatches.ase", None)}


def export(project, formats: list[str], out_dir: Path | None = None, scales: bool = False) -> dict:
    from . import design as D

    d = D.load(project)
    ctx = D.context(project, d)
    t = collect(ctx, scales)
    out_dir = out_dir or project.path("output", "tokens")
    out_dir.mkdir(parents=True, exist_ok=True)
    files = []
    group = d.get("brand") or d.get("name") or project.name
    for f in formats:
        if f not in FORMATS:
            raise SystemExit(f"--to must be among {', '.join(FORMATS)}")
        fname, fn = FORMATS[f]
        path = out_dir / fname
        if f == "ase":
            path.write_bytes(to_ase(t, ctx, group))
        else:
            path.write_text(fn(t, ctx), encoding="utf-8")
        files.append(project.rel(path))
    return {"files": files, "colors": {n: c.hex for n, c in t["colors"].items()},
            "fonts": {n: f"{f['family']} {f['weight']}" for n, f in t["fonts"].items()}}


def cmd_tokens(a):
    from .project import Project

    pr = Project(a.project)
    return export(pr, a.to, pr.abs(a.out) if a.out else None, a.scales)


def register(sub) -> None:
    p = sub.add_parser("tokens", help="colour/font tokens as css, scss, tailwind, json, figma (Tokens Studio), ase swatches")
    p.add_argument("project")
    p.add_argument("--to", nargs="+", default=["css", "json", "ase"], choices=list(FORMATS))
    p.add_argument("--out", help="folder (default output/tokens), project-relative")
    p.add_argument("--scales", action="store_true", help="add 50-950 OKLCH scales of each brand colour")
    p.set_defaults(func=cmd_tokens)
